#!/usr/bin/env python3
"""Build solder paste stencil files for the NG_WPI_7seg_PCB clock board.

Reads the SMD pads straight from the KiCad board file and writes:

  out/jlc/       Gerbers (reduced apertures) + Edge_Cuts, zipped, for ordering a steel stencil
  out/laser/     SVG + DXF (1:1, mm) for laser cutting Mylar / Kapton / thin brass
  out/print/     STL of a resin-printable stencil with a locating lip, plus a board jig
  out/preview_*.png

Aperture rules (tuned for a 0.12 mm steel foil; see README.md):
  TQFP-44 (0.8 mm pitch)     0.55 x 1.50  ->  0.48 x 1.45
  USB micro-B signal (0.65)  0.40 x 1.40  ->  0.32 x 1.30
  pads >= 1.7 mm both ways   inset 0.10 mm per side (crystal, USB shell tabs)
  everything else            inset 0.05 mm per side (~10% area cut)

Requires: pip install sexpdata shapely ezdxf matplotlib manifold3d
"""
import json
import math
import os
import sys
import zipfile
from pathlib import Path

import sexpdata
from sexpdata import Symbol
from shapely.geometry import Polygon, box
from shapely.affinity import rotate, translate
from shapely.ops import unary_union

HERE = Path(__file__).resolve().parent
PCB = HERE.parent / "pcb" / "source (kicad files)" / "NG_WPI_7seg_PCB.kicad_pcb"
OUT = HERE / "out"

# Board outline (Edge.Cuts gr_rect) in KiCad coordinates
BX0, BY0, BW, BH = 48.006, 125.292, 102.0, 40.0
BOARD_T = 1.6


# ---------------------------------------------------------------- parse KiCad
def _name(x):
    return x[0].value() if isinstance(x, list) and x and isinstance(x[0], Symbol) else None


def _find(x, n):
    return [c for c in x if _name(c) == n]


def _one(x, n):
    r = _find(x, n)
    return r[0] if r else None


def load_pads(path=PCB):
    d = sexpdata.loads(Path(path).read_text())
    pads = []
    for fp in _find(d, "footprint"):
        at = _one(fp, "at")
        fx, fy = float(at[1]), float(at[2])
        frot = float(at[3]) if len(at) > 3 else 0.0
        ref = "?"
        for p in _find(fp, "property"):
            if p[1] == "Reference":
                ref = str(p[2])
        lib = str(fp[1]).split(":")[-1]
        for pad in _find(fp, "pad"):
            layers = [str(l) for l in _one(pad, "layers")[1:]]
            paste = [l for l in layers if "Paste" in l]
            if not paste:
                continue
            if "*.Paste" in paste or "F&B.Paste" in paste:
                paste = ["F.Paste", "B.Paste"]
            pat = _one(pad, "at")
            px, py = float(pat[1]), float(pat[2])
            prot = float(pat[3]) if len(pat) > 3 else 0.0  # absolute in KiCad 6+
            sz = _one(pad, "size")
            rr = _one(pad, "roundrect_rratio")
            a = math.radians(frot)
            pads.append(dict(
                ref=ref, pad=str(pad[1]), lib=lib, layers=paste,
                shape=pad[3].value(),
                x=fx + px * math.cos(a) + py * math.sin(a),
                y=fy - px * math.sin(a) + py * math.cos(a),
                rot=prot, w=float(sz[1]), h=float(sz[2]),
                rr=float(rr[1]) if rr else 0.0,
            ))
    return pads


# ---------------------------------------------------------- aperture rules
def aperture_size(p):
    """Return (w, h, rule) of the stencil opening in the pad's own frame."""
    w, h = p["w"], p["h"]
    if p["lib"].startswith("TQFP-44"):
        # pad is 1.5 x 0.55 (long axis = w)
        return (1.45, 0.48, "QFP 0.8 mm: width 0.48, length 1.45") if w > h else (0.48, 1.45, "QFP")
    if p["lib"].startswith("USB_Micro") and min(w, h) < 0.5:
        return (0.32, 1.30, "USB 0.65 mm: width 0.32, length 1.30") if w < h else (1.30, 0.32, "USB")
    if min(w, h) >= 1.7:
        return (w - 0.2, h - 0.2, "large pad: -0.10 mm/side")
    return (w - 0.1, h - 0.1, "default: -0.05 mm/side")


def aperture_poly(p):
    w, h, _ = aperture_size(p)
    if p["shape"] == "roundrect" and p["rr"] > 0:
        r = p["rr"] * min(p["w"], p["h"])  # keep the pad's own corner radius
        r = min(r, min(w, h) / 2 - 1e-3)
        g = box(-w / 2 + r, -h / 2 + r, w / 2 - r, h / 2 - r).buffer(r, quad_segs=8)
    else:
        g = box(-w / 2, -h / 2, w / 2, h / 2)
    # KiCad: y down, positive angle = CCW on screen -> CW in y-down math
    g = rotate(g, -p["rot"], origin=(0, 0))
    return translate(g, p["x"], p["y"])


def pad_poly(p):
    g = box(-p["w"] / 2, -p["h"] / 2, p["w"] / 2, p["h"] / 2)
    return translate(rotate(g, -p["rot"], origin=(0, 0)), p["x"], p["y"])


# ----------------------------------------------------------------- writers
def to_board(g):
    """KiCad coords -> board-local coords (origin top-left, y down)."""
    return translate(g, -BX0, -BY0)


def polys(geom):
    return list(geom.geoms) if hasattr(geom, "geoms") else [geom]


def write_gerber(path, apertures, function):
    L = [
        "G04 Solder paste stencil, generated by hardware/stencil/build_stencil.py*",
        f"%TF.FileFunction,{function}*%",
        "%TF.FilePolarity,Positive*%",
        "%FSLAX46Y46*%", "%MOMM*%", "%LPD*%",
        "%ADD10C,0.010000*%", "D10*", "G01*",
    ]
    c = lambda v: f"{int(round(v * 1e6))}"
    for g in apertures:
        pts = list(g.exterior.coords)
        L.append("G36*")
        L.append(f"X{c(pts[0][0])}Y{c(-pts[0][1])}D02*")
        for x, y in pts[1:]:
            L.append(f"X{c(x)}Y{c(-y)}D01*")
        L.append("G37*")
    L.append("M02*")
    Path(path).write_text("\n".join(L) + "\n")


def write_edge_gerber(path):
    c = lambda v: f"{int(round(v * 1e6))}"
    pts = [(BX0, BY0), (BX0 + BW, BY0), (BX0 + BW, BY0 + BH), (BX0, BY0 + BH), (BX0, BY0)]
    L = ["%TF.FileFunction,Profile,NP*%", "%FSLAX46Y46*%", "%MOMM*%", "%LPD*%",
         "%ADD10C,0.100000*%", "D10*", "G01*", f"X{c(pts[0][0])}Y{c(-pts[0][1])}D02*"]
    L += [f"X{c(x)}Y{c(-y)}D01*" for x, y in pts[1:]]
    L.append("M02*")
    Path(path).write_text("\n".join(L) + "\n")


SHEET_MARGIN = 15.0  # laser sheet extends this far past the board


def write_svg_dxf(stem, apertures, mirror):
    import ezdxf

    def tf(x, y):  # board-local, optionally mirrored for a back-side stencil viewed from the back
        return (BW - x if mirror else x), y

    sx0, sy0 = -SHEET_MARGIN, -SHEET_MARGIN
    sw, sh = BW + 2 * SHEET_MARGIN, BH + 2 * SHEET_MARGIN
    # SVG (mm, 1:1). Red = cut, blue = board outline reference (do not cut).
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{sw}mm" height="{sh}mm" '
         f'viewBox="{sx0} {sy0} {sw} {sh}">',
         f'<rect x="{sx0}" y="{sy0}" width="{sw}" height="{sh}" fill="none" stroke="#ff0000" stroke-width="0.05"/>',
         f'<rect x="0" y="0" width="{BW}" height="{BH}" fill="none" stroke="#0000ff" stroke-width="0.05" stroke-dasharray="1 1"/>']
    for g in apertures:
        pts = " ".join(f"{a:.4f},{b:.4f}" for a, b in (tf(*q) for q in to_board(g).exterior.coords))
        s.append(f'<polygon points="{pts}" fill="none" stroke="#ff0000" stroke-width="0.02"/>')
    s.append("</svg>")
    Path(f"{stem}.svg").write_text("\n".join(s))

    doc = ezdxf.new("R2010", setup=False)
    doc.units = ezdxf.units.MM
    for n, col in (("APERTURES", 1), ("SHEET_OUTLINE", 1), ("BOARD_OUTLINE_REF", 5)):
        doc.layers.add(n, color=col)
    msp = doc.modelspace()
    fy = lambda p: (p[0], -p[1])  # DXF is y-up
    msp.add_lwpolyline([fy(p) for p in [(sx0, sy0), (sx0 + sw, sy0), (sx0 + sw, sy0 + sh), (sx0, sy0 + sh)]],
                       close=True, dxfattribs={"layer": "SHEET_OUTLINE"})
    msp.add_lwpolyline([fy(p) for p in [(0, 0), (BW, 0), (BW, BH), (0, BH)]],
                       close=True, dxfattribs={"layer": "BOARD_OUTLINE_REF"})
    for g in apertures:
        msp.add_lwpolyline([fy(tf(*q)) for q in list(to_board(g).exterior.coords)[:-1]],
                           close=True, dxfattribs={"layer": "APERTURES"})
    doc.saveas(f"{stem}.dxf")


# ---------------------------------------------------------- 3D printed parts
PLATE_T = 0.20      # stencil thickness (resin print)
LIP_GAP = 0.15      # clearance between lip and board edge
LIP_W = 2.0
LIP_DEPTH = 1.2     # less than board thickness so the plate rests on the board
PRINT_MARGIN = 6.0  # plate border outside the lip


def _cs(geoms):
    from manifold3d import CrossSection, FillRule
    loops = []
    for g in geoms:
        for p in polys(g):
            loops.append([list(c) for c in list(p.exterior.coords)[:-1]])
            for i in p.interiors:
                loops.append([list(c) for c in list(i.coords)[:-1]])
    return CrossSection(loops, FillRule.EvenOdd)


def write_stl(path, mesh):
    import numpy as np
    m = mesh.to_mesh()
    v = np.asarray(m.vert_properties)[:, :3]
    t = np.asarray(m.tri_verts)
    with open(path, "wb") as f:
        f.write(b"\0" * 80)
        f.write(np.uint32(len(t)).tobytes())
        rec = np.zeros(len(t), dtype=[("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")])
        tri = v[t]
        n = np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0])
        n /= np.maximum(np.linalg.norm(n, axis=1)[:, None], 1e-12)
        rec["n"], rec["v"] = n, tri
        f.write(rec.tobytes())


def build_printed_stencil(path, apertures, mirror):
    """Thin plate with apertures and a lip that drops over the board edge.

    Printed lip-up: the plate face that touches the board is z=0..PLATE_T,
    the lip rises from it. Flip it over to use."""
    from manifold3d import Manifold
    ap = [to_board(g) for g in apertures]
    if mirror:
        from shapely.affinity import scale
        ap = [scale(g, -1, 1, origin=(BW / 2, 0)) for g in ap]
    # flip y so the STL reads the right way round (y-up in CAD)
    from shapely.affinity import scale as sc
    ap = [sc(g, 1, -1, origin=(0, 0)) for g in ap]
    o = LIP_GAP + LIP_W + PRINT_MARGIN
    plate_outline = box(-o, -BH - o, BW + o, o)
    plate = plate_outline.difference(unary_union(ap))
    m = _cs([plate]).extrude(PLATE_T)
    lip_in = box(-LIP_GAP, -BH - LIP_GAP, BW + LIP_GAP, LIP_GAP)
    lip = lip_in.buffer(LIP_W, join_style=2).difference(lip_in)
    m = m + _cs([lip]).extrude(LIP_DEPTH).translate([0, 0, PLATE_T])
    # stiffening rim on the outer border
    rim_out = plate_outline
    rim = rim_out.difference(rim_out.buffer(-3.0, join_style=2))
    m = m + _cs([rim]).extrude(LIP_DEPTH + 0.8).translate([0, 0, PLATE_T])
    write_stl(path, m)


def build_jig(path, back_side_pads):
    """Flat nest that holds the bare board flush with its top surface.

    Pockets on the floor clear the back-side buttons if they are already fitted."""
    from manifold3d import Manifold
    G, M, BASE = 0.15, 15.0, 6.0
    outer = box(-M, -BH - M, BW + M, M)
    pocket = box(-G, -BH - G, BW + G, G)
    m = _cs([outer]).extrude(BASE)
    m = m + _cs([outer.difference(pocket)]).extrude(BOARD_T).translate([0, 0, BASE])
    # button clearance pockets (PTS647 body 4.5x4.5, give 6.5x6.5) cut into the floor
    from shapely.affinity import scale as sc
    cuts = []
    refs = {}
    for p in back_side_pads:
        refs.setdefault(p["ref"], []).append((p["x"] - BX0, p["y"] - BY0))
    for pts in refs.values():
        cx = sum(a for a, _ in pts) / len(pts)
        cy = sum(b for _, b in pts) / len(pts)
        # jig is viewed from the board's front; back parts are at the same x,y
        cuts.append(box(cx - 3.25, -cy - 3.25, cx + 3.25, -cy + 3.25))
    # finger notches on the long sides to lift the board out
    cuts.append(box(BW / 2 - 8, G - 0.01, BW / 2 + 8, 6))
    cuts.append(box(BW / 2 - 8, -BH - 6, BW / 2 + 8, -BH - G + 0.01))
    cut = _cs([unary_union(cuts)]).extrude(BASE + BOARD_T + 1).translate([0, 0, 0.6])
    m = m - cut
    write_stl(path, m)


# ------------------------------------------------------------------ preview
def preview(path, pads, apertures, title, mirror=False):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Polygon as MP, Rectangle

    fig, ax = plt.subplots(figsize=(13, 5.6), dpi=150)
    ax.add_patch(Rectangle((0, 0), BW, BH, fill=True, fc="#1f5f3a", ec="k"))
    tfx = (lambda x: BW - x) if mirror else (lambda x: x)
    for p in pads:
        g = to_board(pad_poly(p))
        ax.add_patch(MP([(tfx(a), b) for a, b in g.exterior.coords], fc="#d9a441", ec="none"))
    for g in apertures:
        g = to_board(g)
        ax.add_patch(MP([(tfx(a), b) for a, b in g.exterior.coords], fc="#e8e8e8", ec="k", lw=0.2))
    ax.set_xlim(-2, BW + 2)
    ax.set_ylim(BH + 2, -2)
    ax.set_aspect("equal")
    ax.set_title(title)
    ax.set_xlabel("mm (gold = copper pad, grey = stencil opening)")
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


# --------------------------------------------------------------------- main
def main():
    pads = load_pads()
    top = [p for p in pads if "F.Paste" in p["layers"]]
    bot = [p for p in pads if "B.Paste" in p["layers"]]
    ap_top = [aperture_poly(p) for p in top]
    ap_bot = [aperture_poly(p) for p in bot]

    for d in ("jlc", "laser", "print"):
        (OUT / d).mkdir(parents=True, exist_ok=True)

    # sanity: minimum web between openings
    def min_web(aps):
        best = (9e9, None)
        for i, a in enumerate(aps):
            for b in aps[i + 1:]:
                if a.distance(b) < best[0] and a.bounds[0] - 3 < b.bounds[0] < a.bounds[2] + 3:
                    best = (a.distance(b), (a.centroid.coords[0], b.centroid.coords[0]))
        return best[0]

    rules = {}
    for p in pads:
        w, h, r = aperture_size(p)
        key = (p["lib"], p["w"], p["h"])
        rules.setdefault(key, [r, w, h, 0, set()])
        rules[key][3] += 1
        rules[key][4].add(p["ref"])
    summary = {
        "top_openings": len(ap_top), "bottom_openings": len(ap_bot),
        "min_web_top_mm": round(min_web(ap_top), 3), "min_web_bottom_mm": round(min_web(ap_bot), 3),
        "rules": [dict(footprint=k[0], pad=f"{k[1]} x {k[2]}", opening=f"{round(min(v[1], v[2]), 3)} x {round(max(v[1], v[2]), 3)}",
                       rule=v[0], count=v[3], refs=sorted(v[4])) for k, v in rules.items()],
    }
    (OUT / "summary.json").write_text(json.dumps(summary, indent=1))

    # Gerbers for a steel stencil
    write_gerber(OUT / "jlc" / "clock_stencil-F_Paste.gtp", ap_top, "Paste,Top")
    write_gerber(OUT / "jlc" / "clock_stencil-B_Paste.gbp", ap_bot, "Paste,Bot")
    write_edge_gerber(OUT / "jlc" / "clock_stencil-Edge_Cuts.gm1")
    with zipfile.ZipFile(OUT / "jlc" / "clock_stencil_gerbers.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for f in ("clock_stencil-F_Paste.gtp", "clock_stencil-B_Paste.gbp", "clock_stencil-Edge_Cuts.gm1"):
            z.write(OUT / "jlc" / f, f)

    # Laser files
    write_svg_dxf(OUT / "laser" / "stencil_top", ap_top, mirror=False)
    write_svg_dxf(OUT / "laser" / "stencil_bottom_mirrored", ap_bot, mirror=True)

    # 3D printed
    build_printed_stencil(OUT / "print" / "stencil_top_resin.stl", ap_top, mirror=False)
    build_printed_stencil(OUT / "print" / "stencil_bottom_resin.stl", ap_bot, mirror=True)
    build_jig(OUT / "print" / "board_jig.stl", bot)

    preview(OUT / "preview_top.png", top, ap_top, f"Top stencil: {len(ap_top)} openings")
    preview(OUT / "preview_bottom.png", bot, ap_bot, f"Bottom stencil (viewed from back): {len(ap_bot)} openings", mirror=True)
    print(json.dumps({k: v for k, v in summary.items() if k != "rules"}, indent=1))


if __name__ == "__main__":
    main()
